#!/bin/sh
# Build the gateway image for one board inside the kas container.
#
#   scripts/build.sh [--dev] [BOARD] [kas command]
#
# BOARD names a file in kas/boards/ (default: beaglebone-black). The kas
# command defaults to "build"; "shell" opens a bitbake shell for the board,
# "lock" refreshes the board's pinned layer revisions.
#
# --dev builds the netboot variant (kas/dev.yml) in build/<BOARD>-dev: the SD
# card only boots U-Boot, which loads the kernel over TFTP and mounts the root
# filesystem over NFS from this host (scripts/netboot.sh serves both). The
# host's address is detected; set NETBOOT_SERVER to override it (remembered
# per board, NETBOOT_SERVER=auto detects again), e.g. NETBOOT_SERVER=10.42.0.1
# for a board cabled straight to this host (README, "Direct cable").
#
# Only Docker (or Podman) is needed on the host. Everything lands in build/:
# downloads and sstate are shared between boards, the build directory is per
# board (build/<board>/tmp/deploy/images/ holds the images).
set -eu

KAS_VERSION=5.5
KAS_CONTAINER_SHA256=7a8186f18d14ec6bec3f8d5188eba7a60f1ef4b5587af15917527588cc7d738a

top=$(cd "$(dirname "$0")/.." && pwd)
dev=
if [ "${1:-}" = --dev ]; then
	dev=1
	shift
fi
board=${1:-beaglebone-black}
[ $# -gt 0 ] && shift
cmd=${1:-build}
[ $# -gt 0 ] && shift

board_file=kas/boards/$board.yml
if [ ! -f "$top/$board_file" ]; then
	echo "unknown board '$board'; available:" >&2
	ls "$top/kas/boards" | sed -n 's/\.yml$//p' | grep -v '\.lock$' >&2
	exit 2
fi

kas_container=$top/build/kas-container-$KAS_VERSION
if [ ! -x "$kas_container" ]; then
	mkdir -p "$top/build"
	curl -sSfL -o "$kas_container.tmp" \
		"https://raw.githubusercontent.com/siemens/kas/$KAS_VERSION/kas-container"
	echo "$KAS_CONTAINER_SHA256  $kas_container.tmp" | sha256sum -c --quiet
	chmod +x "$kas_container.tmp"
	mv "$kas_container.tmp" "$kas_container"
fi

config=$board_file
build_dir=$top/build/$board
if [ -n "$dev" ]; then
	if [ "$cmd" = lock ]; then
		echo "lock pins the board's layers; run it without --dev" >&2
		exit 2
	fi
	build_dir=$top/build/$board-dev
	mkdir -p "$build_dir"
	# NETBOOT_SERVER is remembered, so a later build without it does not
	# switch back to the detected address; NETBOOT_SERVER=auto forgets it.
	case ${NETBOOT_SERVER:-} in
	"") ;;
	auto) rm -f "$build_dir/netboot-server" ;;
	*) echo "$NETBOOT_SERVER" > "$build_dir/netboot-server" ;;
	esac
	server=$(cat "$build_dir/netboot-server" 2>/dev/null ||
		ip -4 route get 1.1.1.1 | sed -n 's/.* src \([0-9.]*\).*/\1/p')
	if [ -z "$server" ]; then
		echo "cannot detect this host's address; set NETBOOT_SERVER" >&2
		exit 2
	fi
	cat > "$build_dir/netboot.yml" <<-EOF
		# Generated by scripts/build.sh --dev.
		header:
		  version: 20
		local_conf_header:
		  netboot: |
		    STONE_OCEAN_NETBOOT_SERVER = "$server"
	EOF
	config=$config:kas/dev.yml:build/$board-dev/netboot.yml
fi

export KAS_WORK_DIR="$top/build/layers"
export KAS_BUILD_DIR="$build_dir"
export DL_DIR="$top/build/downloads"
export SSTATE_DIR="$top/build/sstate-cache"
mkdir -p "$KAS_WORK_DIR" "$KAS_BUILD_DIR"

cd "$top"
exec "$kas_container" "$cmd" "$@" "$config"
